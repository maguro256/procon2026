def registered_text():
    db = os.path.join(REPO, "gemmba.db")
    if not os.path.exists(db):
        return ""
    c = sqlite3.connect(db)
    names = [r[0] for r in c.execute("select name from equipment")]
    titles = [r[0] for r in c.execute("select title from tasks")]
    return " ".join(names + titles)


def source(term, reg):
    # 「製品D」は登録データでは「製品D」、固定語彙には無い、のように語ごとに判定する
    s = ("P" if term in FIXED_PROMPT else "") + ("D" if term in reg else "")
    return s or "N"


def main():
    reg = registered_text()
    rows = []
    for kind, items in (("core", CORE), ("synth", SYNTH)):
        for i, text, kw, pri, qty, due, perm, terms in items:
            src = " ".join(f"{t}:{source(t, reg)}" for t in terms.split("|"))
            rows.append({"id": i, "set": kind, "text": text, "title_keywords": kw,
                         "priority": pri, "quantity": qty, "deadline": due,
                         "permissions": perm, "terms": src})
    with open(os.path.join(HERE, "prompts.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)
    with open(os.path.join(HERE, "reading_script.txt"), "w", encoding="utf-8") as f:
        f.write("読み上げ台本（30文）\n番号は読まずに、決定ボタンを押している間に1文ずつ読んでください。\n\n")
        for r in rows:
            if r["set"] == "core":
                f.write(f"{r['id']}  {r['text']}\n")
    n = {k: sum(1 for r in rows if r["set"] == k) for k in ("core", "synth")}
    print(n)
    from collections import Counter
    print("固定語彙/登録データ/なし:", Counter(t.split(":")[1] for r in rows for t in r["terms"].split()))


if __name__ == "__main__":
    main()
